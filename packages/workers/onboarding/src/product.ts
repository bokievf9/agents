export type ProductType = 'site' | 'bot' | 'app' | 'automation' | 'other';

export const PRODUCT_RU: Record<ProductType, string> = { site: 'сайт', bot: 'Telegram-бот', app: 'приложение', automation: 'автоматизация', other: 'проект' };

/** From the free text the owner or the invoice gave ("сайт для салона", "бот записи"). */
export function guessProduct(text: string): ProductType {
  const t = text.toLowerCase();
  if (/бот|\bbot\b/.test(t)) return 'bot';
  if (/автомат|интеграц|automation|парсер|crm/.test(t)) return 'automation';
  if (/приложен|\bapp\b|pwa/.test(t)) return 'app';
  if (/сайт|лендинг|landing|site|web|магазин/.test(t)) return 'site';
  return 'other';
}

/** The accesses the owner has to collect or hand over, by product. */
export function accessItems(type: ProductType): string[] {
  switch (type) {
    case 'site':
      return ['Домен (на кого оформлен, доступ к DNS)', 'Хостинг (доступ или передача проекта клиенту)'];
    case 'bot':
      return ['Telegram-бот (токен из @BotFather, владелец бота)', 'Чат или группа для заявок (добавить бота)'];
    case 'app':
      return ['Домен (на кого оформлен, доступ к DNS)', 'Хостинг (доступ или передача проекта клиенту)', 'Telegram-бот или стор-аккаунты, если нужны'];
    case 'automation':
      return ['Доступы к сервисам, которые автоматизируем (отдельные ключи, не личные пароли)', 'Telegram-бот для уведомлений'];
    default:
      return ['Домен', 'Хостинг', 'Telegram-бот'];
  }
}

